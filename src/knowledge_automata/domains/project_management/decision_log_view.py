"""The decision log's Markdown views: an index and one page per decision.

Content is LLM text, so every rendered value is escaped. Rendering is deterministic: no
generation timestamp, and records are sorted by ID.
"""

from collections.abc import Mapping, Sequence
from typing import Any

from knowledge_automata.views.markdown import (
    VIEWS_FOLDER,
    blockquote,
    escape,
    inline,
    relative_link,
    table_row,
)

INDEX = "decision-log.md"
PAGES = "decision-log"
OWNED: tuple[str, ...] = (INDEX, f"{PAGES}/")
"""View files the decision log generator owns, relative to ``<memory>/views/``."""

_INTRO = (
    "Generated from the JSON records in `registers/decision-log/`. Do not edit this file by "
    "hand: run `knowledge-automata views` to regenerate it."
)

# Optional content sections after the statement, in content schema order.
_TEXT_SECTIONS = {"context": "Context", "rationale": "Rationale"}
_TRAILING_SECTIONS = {"decided_on": "Decided on", "impacts": "Impacts"}


def _sequence(record_id: str) -> int:
    return int(record_id.rsplit("-", 1)[1])


def page_path(record_id: str) -> str:
    return f"{PAGES}/{record_id}.md"


def _page_link(from_view: str, record_id: str) -> str:
    return f"[{record_id}]({relative_link(from_view, page_path(record_id))})"


def render_decision_log(
    records: Sequence[Mapping[str, Any]], artifact_links: Mapping[str, str]
) -> dict[str, str]:
    """Map view paths (relative to ``<memory>/views/``) to their content.

    ``artifact_links`` maps an artifact ID to its file path relative to the memory folder;
    artifacts not in the map are shown as plain IDs.
    """
    ordered = sorted(records, key=lambda record: _sequence(record["id"]))
    files = {INDEX: _render_index(ordered)}
    for record in ordered:
        files[page_path(record["id"])] = _render_page(record, artifact_links)
    return files


def _render_index(records: Sequence[Mapping[str, Any]]) -> str:
    lines = ["# Decision log", "", _INTRO, ""]
    if not records:
        lines.append("No decisions recorded yet.")
    else:
        lines.append(table_row(["ID", "Decision", "Decided on", "Status"]))
        lines.append(table_row(["---"] * 4).replace(" ", ""))
        for record in records:
            content = record["content"]
            status = record["record_status"]
            superseded_by = record.get("relations", {}).get("superseded_by")
            if superseded_by:
                status = f"superseded by {_page_link(INDEX, superseded_by)}"
            lines.append(
                table_row(
                    [
                        _page_link(INDEX, record["id"]),
                        inline(content["title"]),
                        inline(content.get("decided_on", "")),
                        status,
                    ]
                )
            )
    return "\n".join(lines) + "\n"


def _render_page(record: Mapping[str, Any], artifact_links: Mapping[str, str]) -> str:
    record_id = record["id"]
    view = page_path(record_id)
    content = record["content"]
    lines = [
        "---",
        f"id: {record_id}",
        f"status: {record['record_status']}",
        f"revision: {record['revision']}",
        f"created: {record['created_at']}",
        f"updated: {record['updated_at']}",
        "---",
        "",
        f"# {record_id}: {inline(content['title'])}",
        "",
        f"Back to the [decision log]({relative_link(view, INDEX)}).",
        "",
    ]

    def section(title: str, body: str) -> None:
        lines.extend([f"## {title}", "", body, ""])

    section("Decision", escape(content["statement"]))
    for field, title in _TEXT_SECTIONS.items():
        if field in content:
            section(title, escape(content[field]))
    if content.get("alternatives"):
        section(
            "Alternatives considered",
            "\n".join(f"- {inline(item)}" for item in content["alternatives"]),
        )
    if content.get("decided_by"):
        section("Decided by", ", ".join(inline(item) for item in content["decided_by"]))
    for field, title in _TRAILING_SECTIONS.items():
        if field in content:
            section(title, escape(content[field]))

    relations = record.get("relations", {})
    related = []
    if relations.get("supersedes"):
        targets = ", ".join(_page_link(view, target) for target in relations["supersedes"])
        related.append(f"- Supersedes {targets}")
    if relations.get("superseded_by"):
        related.append(f"- Superseded by {_page_link(view, relations['superseded_by'])}")
    if related:
        section("Related decisions", "\n".join(related))

    lines.extend(["## Sources", "", *_render_sources(view, record["sources"], artifact_links)])

    lines.extend(
        [
            "## History",
            "",
            table_row(["Revision", "Date", "Change", "Details", "Artifact", "Model", "Prompt"]),
            table_row(["---"] * 7).replace(" ", ""),
        ]
    )
    for entry in record["history"]:
        lines.append(
            table_row(
                [
                    str(entry["revision"]),
                    entry["at"],
                    entry["change"],
                    _details(view, entry),
                    entry["artifact_id"],
                    inline(entry.get("model", "")),
                    inline(entry.get("prompt_version", "")),
                ]
            )
        )
    return "\n".join(lines) + "\n"


def _render_sources(
    view: str, sources: Sequence[Mapping[str, Any]], artifact_links: Mapping[str, str]
) -> list[str]:
    """One heading per artifact, in order of first appearance, then its quotes."""
    groups: dict[str, list[Mapping[str, Any]]] = {}
    for source in sources:
        groups.setdefault(source["artifact_id"], []).append(source)
    lines = []
    for artifact_id, group in groups.items():
        lines.extend([_source_heading(view, artifact_id, group, artifact_links), ""])
        for source in group:
            lines.extend([blockquote(source["excerpt"]), ""])
    return lines


def _source_heading(
    view: str,
    artifact_id: str,
    group: Sequence[Mapping[str, Any]],
    artifact_links: Mapping[str, str],
) -> str:
    label = artifact_id
    if artifact_id in artifact_links:
        target = relative_link(f"{VIEWS_FOLDER}/{view}", artifact_links[artifact_id])
        label = f"[{artifact_id}]({target})"
    date = next((source["artifact_date"] for source in group if "artifact_date" in source), None)
    return f"### {label}, {date}" if date else f"### {label}"


def _details(view: str, entry: Mapping[str, Any]) -> str:
    change = entry["change"]
    if change == "update":
        fields = entry.get("fields", [])
        return f"Filled: {', '.join(fields)}" if fields else "No empty fields filled"
    if change == "supersession" and "related_id" in entry:
        return f"Supersedes {_page_link(view, entry['related_id'])}"
    if change == "superseded" and "related_id" in entry:
        return f"Superseded by {_page_link(view, entry['related_id'])}"
    return ""
